"""Policy reader metrics we can measure without a hand-labeled answer key.

B's data/answer_key.json scores the rules ENGINE on synthetic policies; it has no field labels for real
policy PDFs. So this script reports, for the 6 originally cached real policies:
  1. quote verification: share of "stated" fields whose verbatim quote was found in the PDF text
  2. fields sent to human review (unclear / < 0.8 confidence / unverified)
  3. run-to-run agreement: first run (git 5f461de) vs re-run, on the 5 headline values per policy
The hand spot-checks (Boys Town 6/6, USA Health 5/6) are reported separately in SUMMARY.md, labeled as such.

python -m eval.policy_reader -> eval/results/policy_reader.md
"""

from __future__ import annotations

import json
import subprocess

from backend.policy_reader.cache import REPO_ROOT
from backend.policy_reader.schema import EVIDENCE_FIELDS
from backend import eval_config

ORIGINAL_SIX = ["adena-health-system__98aeefd8", "baptist-memorial-health-care-corporation__a4ba678b",
                "boys-town-national-research-hospital__9bae57a6", "fort-healthcare-inc__5cc2d46b",
                "marshfield-clinic-health-system__e23ca69e", "usa-health__6a0883be"]
FIRST_RUN_COMMIT = "5f461de"
OUT = REPO_ROOT / "eval" / "results" / "policy_reader.md"


def headline(d: dict) -> dict:
    status = lambda f: d[f]["evidence"].get("status", "stated")  # noqa: E731
    return {
        "free %": d["free_care"]["fpl_max_percent"],
        "discount %": d["discount"]["fpl_max_percent"],
        "asset test": eval_config.comparable_value(d["asset_test"]["applies"], status("asset_test")),
        "residency": eval_config.comparable_value(d["residency"]["required"], status("residency")),
        "window days": d["application_window"]["days"],
    }


def main() -> int:
    stated = verified = review = 0
    agree = total = 0
    rows, diffs = [], []
    for name in ORIGINAL_SIX:
        now = json.loads((REPO_ROOT / "cache" / "policies" / f"{name}.json").read_text())
        first = json.loads(subprocess.check_output(["git", "show", f"{FIRST_RUN_COMMIT}:cache/policies/{name}.json"], cwd=REPO_ROOT))
        s = sum(1 for f in EVIDENCE_FIELDS if now[f]["evidence"]["status"] == "stated")
        v = sum(1 for f in EVIDENCE_FIELDS if now[f]["evidence"]["status"] == "stated" and now[f]["evidence"]["verified"])
        stated, verified, review = stated + s, verified + v, review + len(now["review_fields"])
        h1, h2 = headline(first), headline(now)
        same = sum(1 for k in h1 if h1[k] == h2[k])
        agree, total = agree + same, total + len(h1)
        diffs += [(now["hospital_name"], k, h1[k], h2[k]) for k in h1 if h1[k] != h2[k]]
        rows.append(f"| {now['hospital_name']} | {v}/{s} | {len(now['review_fields'])} ({', '.join(now['review_fields']) or '-'}) | {same}/5 |")
    lines = [
        "# Policy reader metrics (6 real policies)", "",
        "No hand-labeled answer key exists for real policy PDFs (B's answer key covers the rules engine on synthetic policies), "
        "so the 120-field accuracy target was **not measured**. These are the numbers we can measure. Generated by `python -m eval.policy_reader`.",
        f"\"Not stated\" mapped to `{eval_config.NOT_STATED_ANSWER_KEY_VALUE}` (backend/eval_config.py).", "",
        f"- Quotes verified verbatim in the PDF text: **{verified}/{stated}** stated fields",
        f"- Fields sent to human review: **{review}/{6 * len(EVIDENCE_FIELDS)}**",
        f"- Run-to-run agreement (first run vs re-run, 5 headline values x 6 policies): **{agree}/{total}**", "",
        "| Policy | Quotes verified | Fields to review | Same as first run |", "|---|---|---|---|", *rows, "",
        "## Values that changed between the two runs", "", "| Policy | Value | First run | Re-run |", "|---|---|---|---|",
        *[f"| {a} | {b} | {c} | {d} |" for a, b, c, d in diffs],
    ]
    if not diffs:
        lines.append("| — | none | | |")
    OUT.write_text("\n".join(lines) + "\n")
    OUT.with_suffix(".json").write_text(json.dumps({"quotes_verified": verified, "stated": stated, "review": review, "fields": 30,
                                                    "agree": agree, "agree_total": total, "not_stated_value": eval_config.NOT_STATED_ANSWER_KEY_VALUE}, indent=2) + "\n")
    print(f"quotes verified {verified}/{stated}; review {review}/30; run agreement {agree}/{total}")
    for d in diffs:
        print("  changed:", d)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
