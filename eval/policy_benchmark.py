"""Policy reader benchmark: score the reader against answers a PERSON verified from each PDF.

    python -m eval.policy_benchmark eval/answer_key_real_TODO.csv --out eval/results/policy_benchmark_6.md
    python -m eval.policy_benchmark eval/verify/answer_key.csv --require-verifier --out eval/results/policy_benchmark_verified.md

A row is scored only when `is_correct` is yes/no (and, with --require-verifier, `verified_by` is filled in).
`is_correct` = n/a (or "not applicable") leaves the row out of the denominator. Blank rows are never counted.
This script never fills answers; it only counts what a person marked.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import OrderedDict
from pathlib import Path
from typing import Any

YES = {"yes", "y", "true", "1", "correct", "right"}
NO = {"no", "n", "false", "0", "wrong", "incorrect"}
NA = {"n/a", "na", "not applicable"}
FIELD_LABELS = {
    "free_care %": "Free-care limit (% of poverty line)",
    "discount max %": "Discount limit (% of poverty line)",
    "discount tiers": "Discount amount (tiers)",
    "asset test": "Asset test",
    "residency": "Residency rule",
    "application window": "Application window",
}


def load_rows(path: Path, require_verifier: bool) -> tuple[list[dict[str, str]], dict[str, int]]:
    """(scored rows, counts of skipped rows by reason). Each scored row gets a bool `_correct`."""
    with path.open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    scored, skipped = [], {"blank": 0, "not_applicable": 0, "no_verifier": 0}
    for row in rows:
        mark = (row.get("is_correct") or "").strip().lower()
        if mark in NA:
            skipped["not_applicable"] += 1
        elif mark not in YES | NO:
            skipped["blank"] += 1
        elif require_verifier and not (row.get("verified_by") or "").strip():
            skipped["no_verifier"] += 1
        else:
            scored.append({**row, "_correct": mark in YES})
    return scored, skipped


def _tally(rows: list[dict[str, Any]], key: str) -> "OrderedDict[str, list[int]]":
    out: OrderedDict[str, list[int]] = OrderedDict()
    for r in rows:
        out.setdefault(r[key], [0, 0])
        out[r[key]][0] += int(r["_correct"])
        out[r[key]][1] += 1
    return out


def _cell(text: str, limit: int = 220) -> str:
    text = " ".join((text or "").split()).replace("|", "\\|")
    return text if len(text) <= limit else text[: limit - 1] + "…"


def report(path: Path, require_verifier: bool, method: str) -> tuple[str, dict[str, Any]]:
    rows, skipped = load_rows(path, require_verifier)
    correct, total = sum(r["_correct"] for r in rows), len(rows)
    policies = list(OrderedDict.fromkeys(r["hospital"] for r in rows))
    n = len(policies)
    noun = "hospital policy" if n == 1 else "hospital policies"
    words = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}
    headline = f"{correct} of {total} scored fields correct across {words.get(n, str(n))} {noun}"
    by_field, by_hosp = _tally(rows, "field"), _tally(rows, "hospital")
    misses = [r for r in rows if not r["_correct"]]
    lines = [
        "# Policy reader benchmark", "",
        f"**{headline}**" + (f" ({correct / total:.0%})." if total else "."), "",
        f"Source: `{path.as_posix()}`. Generated by `python -m eval.policy_benchmark`.",
        f"Rows not scored: {skipped['blank']} blank, {skipped['not_applicable']} marked not applicable"
        + (f", {skipped['no_verifier']} without `verified_by`" if require_verifier else "") + ".", "",
        f"Method: {method}", "",
        "## By field", "", "| Field | Correct |", "|---|---|",
        *[f"| {FIELD_LABELS.get(f, f)} | {c}/{t} |" for f, (c, t) in by_field.items()], "",
        "## By hospital", "", "| Hospital | Correct |", "|---|---|",
        *[f"| {_cell(h, 90)} | {c}/{t} |" for h, (c, t) in by_hosp.items()], "",
        f"## Every miss ({len(misses)})", "",
    ]
    if misses:
        lines += ["| Hospital | Field | Reader said | Correct value | Reader's quote | Page |", "|---|---|---|---|---|---|"]
        lines += [f"| {_cell(r['hospital'], 60)} | {FIELD_LABELS.get(r['field'], r['field'])} | {_cell(r['reader_value'], 160)} | "
                  f"{_cell(r.get('correct_value', ''), 160) or '(not written)'} | {_cell(r.get('reader_quote', ''))} | {r.get('page', '')} |"
                  for r in misses]
    else:
        lines.append("None.")
    data = {"headline": headline, "correct": correct, "total": total, "policies": policies, "skipped": skipped,
            "by_field": by_field, "by_hospital": by_hosp, "source": path.as_posix()}
    return "\n".join(lines) + "\n", data


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--require-verifier", action="store_true", help="count only rows with verified_by filled in")
    parser.add_argument("--method", default="Answers independently verified by a team member reading each PDF; reader outputs "
                        "from our cached Claude Sonnet 5.5 runs (no new AI calls); scored by `eval/policy_benchmark.py`.")
    args = parser.parse_args()
    md, data = report(args.csv, args.require_verifier, args.method)
    args.out.write_text(md)
    args.out.with_suffix(".json").write_text(json.dumps(data, indent=2) + "\n")
    print(data["headline"], "| skipped:", data["skipped"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
