"""Bill extraction eval: bill reader on C's 10 fictional sample bills vs sample_bills/answer_key.csv.

python -m eval.bill_extraction [--save-cache]   (live model calls, ~1 cent per bill)
Writes eval/results/bill_extraction.md and eval/results/bill_extraction.json.
--save-cache also stores each result in cache/bills/<sha256>.json for BILL_CACHE_ONLY demo mode.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import mimetypes
import re
import time
from pathlib import Path

from rapidfuzz import fuzz

from backend import pricing
from backend.bill_reader.reader import read_bill
from backend.demo_mode import BILL_CACHE_DIR
from backend.policy_reader.cache import REPO_ROOT

BILLS = REPO_ROOT / "sample_bills"
OUT = REPO_ROOT / "eval" / "results"
FIELDS = ("hospital_name", "hospital_address", "amount_due", "service_date", "account_number")
ADDRESS_MIN = 90


def norm_text(s: str | None) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[.,]", " ", (s or "").lower())).strip()


def correct(field: str, got: dict, row: dict) -> bool:
    if field == "amount_due":
        return got.get("normalized") == int(row["amount_due_cents"])
    if field == "service_date":
        return got.get("normalized") == row["service_date"]
    if field == "hospital_address":
        return fuzz.token_sort_ratio(norm_text(got.get("value")), norm_text(row["hospital_address"])) >= ADDRESS_MIN
    return norm_text(got.get("value")) == norm_text(row[field])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--save-cache", action="store_true")
    args = ap.parse_args()
    rows = list(csv.DictReader((BILLS / "answer_key.csv").open()))
    results = []
    for row in rows:
        path = BILLS / row["file"]
        data = path.read_bytes()
        start = time.perf_counter()
        res = read_bill(data, mimetypes.guess_type(path.name)[0] or "")
        seconds = time.perf_counter() - start
        out = res.to_dict()
        if args.save_cache:
            BILL_CACHE_DIR.mkdir(parents=True, exist_ok=True)
            (BILL_CACHE_DIR / f"{hashlib.sha256(data).hexdigest()}.json").write_text(json.dumps(out, indent=2) + "\n")
        checks = {f: correct(f, out["fields"][f], row) for f in FIELDS}
        results.append({
            "file": row["file"], "condition": row["condition"], "checks": checks, "fields": out["fields"],
            "fields_to_confirm": out["fields_to_confirm"], "seconds": seconds,
            "cost": pricing.estimate_cost_usd(res.model, res.input_tokens, res.output_tokens) or 0.0,
            "tokens_in": res.input_tokens, "tokens_out": res.output_tokens,
        })
        print(f"{row['file']:28} {sum(checks.values())}/5  {seconds:.1f}s  confirm={out['fields_to_confirm']}")
    write_report(results, rows)
    return 0


def write_report(results: list[dict], rows: list[dict]) -> None:
    total = sum(sum(r["checks"].values()) for r in results)
    n = len(results) * len(FIELDS)
    by_field = {f: sum(r["checks"][f] for r in results) for f in FIELDS}
    by_cond: dict[str, list[int]] = {}
    for r in results:
        c = by_cond.setdefault(r["condition"], [0, 0])
        c[0] += sum(r["checks"].values())
        c[1] += len(FIELDS)
    low = sum(1 for r in results for f in FIELDS if r["fields"][f]["confidence"] < 0.8)
    confirm = sum(len(r["fields_to_confirm"]) for r in results)
    secs = [r["seconds"] for r in results]
    costs = [r["cost"] for r in results]
    key = {row["file"]: row for row in rows}
    lines = [
        "# Bill extraction eval",
        "",
        f"Bill reader (Claude Sonnet 5.5) on C's 10 fictional sample bills vs `sample_bills/answer_key.csv`. Generated by `python -m eval.bill_extraction`.",
        "",
        f"**Overall: {total}/{n} fields correct ({100 * total / n:.1f}%).**",
        "",
        "| Field | Correct |", "|---|---|",
        *[f"| {f} | {by_field[f]}/{len(results)} |" for f in FIELDS],
        "",
        "| Photo condition | Correct |", "|---|---|",
        *[f"| {c} | {v[0]}/{v[1]} |" for c, v in by_cond.items()],
        "",
        f"- Seconds per bill (bill read only): avg {sum(secs) / len(secs):.1f}, max {max(secs):.1f}",
        f"- Cost per bill read: avg ${sum(costs) / len(costs):.4f}, max ${max(costs):.4f}",
        f"- Fields under 0.8 confidence: {low}/{n}; fields sent to the patient to confirm (incl. failed checks): {confirm}/{n}",
        "",
        "Rules: amounts compared in cents, dates as ISO, names/account numbers case- and whitespace-insensitive, address fuzzy (token_sort_ratio) ≥ 90.",
        "",
        "## Every miss",
        "",
        "| Bill | Field | Expected | Got | Confidence |", "|---|---|---|---|---|",
    ]
    for r in results:
        for f in FIELDS:
            if not r["checks"][f]:
                exp = key[r["file"]]["amount_due_cents" if f == "amount_due" else f]
                got = r["fields"][f]
                shown = got.get("normalized") if f in ("amount_due", "service_date") else got.get("value")
                lines.append(f"| {r['file']} | {f} | {exp} | {shown} | {got['confidence']} |")
    if total == n:
        lines.append("| — | none | | | |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "bill_extraction.md").write_text("\n".join(lines) + "\n")
    (OUT / "bill_extraction.json").write_text(json.dumps(results, indent=2) + "\n")
    print(f"\nTOTAL {total}/{n}  avg {sum(secs) / len(secs):.1f}s  avg ${sum(costs) / len(costs):.4f}  low-conf {low}  confirm {confirm}")


if __name__ == "__main__":
    raise SystemExit(main())
