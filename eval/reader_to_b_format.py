"""Convert the 14 successful real-policy reads into B's HospitalPolicy JSON, then run B's scorer on them.

    python -m eval.reader_to_b_format

Writes data/person_a_output/HOSP-R###.json (B's format, via backend.eligibility.policy_rules_to_hospital_policy)
and eval/results/b_scorer_on_reader_output.md. No API calls: it uses the cached reads in cache/policies.

The scorer checks completeness, format and internal consistency. It does NOT check that values are
right against the PDF, so its number is a completeness/format score, not accuracy.
"""

from __future__ import annotations

import dataclasses
import json
from decimal import Decimal
from enum import Enum
from pathlib import Path
from typing import Any

from backend.eligibility import policy_rules_to_hospital_policy
from backend.policy_reader.cache import DEFAULT_CACHE_DIR, REPO_ROOT
from backend.policy_reader.schema import PolicyRules
from billback.scorer import score_all_policies

REAL = REPO_ROOT / "data" / "real-policies"
OUT_DIR = REPO_ROOT / "data" / "person_a_output"
REPORT = REPO_ROOT / "eval" / "results" / "b_scorer_on_reader_output.md"


def _plain(value: Any) -> Any:
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    return value


def _cached_rules_by_url() -> dict[str, PolicyRules]:
    out: dict[str, PolicyRules] = {}
    for path in Path(DEFAULT_CACHE_DIR).glob("*__*.json"):
        rules = PolicyRules.model_validate_json(path.read_text())
        if rules.source and rules.source.url:
            out[rules.source.url] = rules
    return out


def _match(meta: dict[str, Any], by_url: dict[str, PolicyRules]) -> PolicyRules | None:
    url = meta.get("source_url") or ""
    if url in by_url:
        return by_url[url]
    # The fetcher may follow a landing page to the PDF; fall back to the hospital name.
    name = meta["hospital_name"].lower()
    for rules in by_url.values():
        if name in rules.hospital_name.lower() or rules.hospital_name.lower() in name:
            return rules
    first = name.split()[0]
    hits = [r for r in by_url.values() if r.hospital_name.lower().split()[0] == first]
    return hits[0] if len(hits) == 1 else None


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    by_url = _cached_rules_by_url()
    converted, missing = [], []
    for path in sorted(REAL.glob("HOSP-R*.json")):
        meta = json.loads(path.read_text())
        rules = _match(meta, by_url)
        if rules is None:
            missing.append(meta["policy_id"])
            continue
        policy = policy_rules_to_hospital_policy(rules)
        data = _plain(dataclasses.asdict(policy))
        data["policy_id"] = meta["policy_id"]
        data["state"] = data.get("state") or meta["state"]
        data["verification_status"] = "read_by_policy_reader"
        (OUT_DIR / f"{meta['policy_id']}.json").write_text(json.dumps(data, indent=2) + "\n")
        converted.append(meta["policy_id"])

    scores = score_all_policies(OUT_DIR)
    lines = [
        "# B's scorer on the policy reader's output (completeness/format score, not accuracy)",
        "",
        "Generated by `python -m eval.reader_to_b_format`, then `python -m billback.scorer data/person_a_output`.",
        "",
        "**What this measures:** B's scorer checks that each policy JSON is complete, well-formed and internally",
        "consistent (required fields, valid enums, ordered tiers, evidence references). It does **not** compare",
        "values with the PDF, so this is a **completeness/format score, not accuracy**.",
        "",
        f"Converted {len(converted)} reads into B's `HospitalPolicy` format (`data/person_a_output/`).",
        f"Not converted (the hospital site blocked the download or moved the policy): {', '.join(missing) or 'none'}.",
        "",
        "| policy | hospital | score /100 | passed | errors | warnings |",
        "|---|---|---|---|---|---|",
    ]
    total, passed = 0.0, 0
    for pid in converted:
        s = scores.get(pid)
        if s is None:
            continue
        summary = s.to_dict()["summary"]
        hospital = json.loads((OUT_DIR / f"{pid}.json").read_text())["hospital_name"]
        lines.append(f"| {pid} | {hospital} | {s.total_score:.1f} | {'yes' if s.passed else 'no'} | {summary['errors']} | {summary['warnings']} |")
        total += s.total_score
        passed += int(s.passed)
    n = len([p for p in converted if p in scores])
    if n:
        lines += [
            "",
            f"**Average completeness/format score: {total / n:.1f}/100; {passed}/{n} passed B's scorer.**",
            "",
            "Why none pass: every policy loses points for `version` being null, and some for `effective_date`.",
            "Our reader's schema has no policy-version field, and some policies don't state an effective date, so",
            "the adapter leaves them null rather than guessing. Those are format gaps, not wrong values.",
            "HOSP-R016 (Duke) is the application form, not the policy, so its tiers are empty; it is flagged for review.",
        ]
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
