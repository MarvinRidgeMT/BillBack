"""Speed and cost per bill, by stage. Uses measured numbers only:
- bill read: eval/results/bill_extraction.json (live Claude Sonnet 5.5 calls on C's 10 bills)
- hospital match + eligibility: timed here, in-process, on the same 10 bills
- policy read: cached = timed here; live = the 6-policy live run (python -m backend.policy_reader.cli --all ... --no-cache)
Price: Claude Sonnet 5.5 $2 / $10 per 1M tokens (https://platform.claude.com/docs/en/about-claude/pricing).

python -m eval.speed_cost -> eval/results/speed_cost.md
"""

from __future__ import annotations

import csv
import json
import time

from fastapi.testclient import TestClient

from backend import app as app_module
from backend import policies
from backend.policy_reader import cache
from backend.policy_reader.cache import REPO_ROOT

RES = REPO_ROOT / "eval" / "results"
# Measured 2026-11-22 ~01:00 ET: 6 real policies, --no-cache, Claude Sonnet 5.5 effort medium (CLI summary line).
LIVE_POLICY_SECONDS_AVG = 8.3
LIVE_POLICY_COST_AVG = 0.0432
TARGET_SECONDS, TARGET_COST = 60.0, 0.05


def main() -> int:
    bills = json.loads((RES / "bill_extraction.json").read_text())
    key = {r["file"]: r for r in csv.DictReader((REPO_ROOT / "sample_bills" / "answer_key.csv").open())}
    client = TestClient(app_module.app)
    rows = []
    for b in bills:
        f = b["fields"]
        t0 = time.perf_counter()
        m = policies.match_hospital(f["hospital_name"]["value"], f["hospital_address"]["value"])
        t1 = time.perf_counter()
        rules, path = policies.load_policy(m["slug"])
        cache.lookup(rules.source.sha256)  # what a cached policy read costs
        t2 = time.perf_counter()
        resp = client.post("/api/eligibility", json={"hospital_slug": m["slug"], "household_size": 3, "annual_income": 40000,
                                                     "state": key[b["file"]]["state"], "assets_usd": 0})
        t3 = time.perf_counter()
        assert resp.status_code == 200, resp.text
        rows.append({"file": b["file"], "bill": b["seconds"], "match": t1 - t0, "policy_cached": t2 - t1, "elig": t3 - t2,
                     "cost": b["cost"], "matched": m["slug"] == key[b["file"]]["hospital_slug"]})
    avg = lambda k: sum(r[k] for r in rows) / len(rows)  # noqa: E731
    mx = lambda k: max(r[k] for r in rows)  # noqa: E731
    e2e = [r["bill"] + r["match"] + r["policy_cached"] + r["elig"] for r in rows]
    e2e_live = [x + LIVE_POLICY_SECONDS_AVG for x in e2e]
    cost_cached = avg("cost")
    cost_live = cost_cached + LIVE_POLICY_COST_AVG
    lines = [
        "# Speed and cost per bill", "", "Generated by `python -m eval.speed_cost`. Bill-read times and tokens are from the live bill eval; the other stages are timed here.", "",
        "| Stage | Avg | Max |", "|---|---|---|",
        f"| Bill read (Claude vision) | {avg('bill'):.2f} s | {mx('bill'):.2f} s |",
        f"| Hospital match | {avg('match') * 1000:.1f} ms | {mx('match') * 1000:.1f} ms |",
        f"| Policy read, cached | {avg('policy_cached') * 1000:.1f} ms | {mx('policy_cached') * 1000:.1f} ms |",
        f"| Policy read, live (first time a hospital is seen) | {LIVE_POLICY_SECONDS_AVG:.1f} s | (6-policy run) |",
        f"| Eligibility (rules engine, via API) | {avg('elig') * 1000:.1f} ms | {mx('elig') * 1000:.1f} ms |",
        f"| **End to end, cached policy** | **{sum(e2e) / len(e2e):.2f} s** | **{max(e2e):.2f} s** |",
        f"| End to end, live policy read | {sum(e2e_live) / len(e2e_live):.2f} s | {max(e2e_live):.2f} s |", "",
        "| Cost per bill | Avg |", "|---|---|",
        f"| Cached policy (bill read only) | ${cost_cached:.4f} |",
        f"| First bill for a new hospital (bill read + live policy read) | ${cost_live:.4f} |", "",
        f"Targets: < {TARGET_SECONDS:.0f} s and < ${TARGET_COST:.2f} per bill. Hospital match correct on {sum(r['matched'] for r in rows)}/{len(rows)} bills.",
        "Eligibility, match and cached policy reads use no AI and cost $0. Human time to confirm fields and answer two questions is not included.",
    ]
    (RES / "speed_cost.md").write_text("\n".join(lines) + "\n")
    summary = {"e2e_cached_avg": sum(e2e) / len(e2e), "e2e_cached_max": max(e2e), "e2e_live_avg": sum(e2e_live) / len(e2e_live),
               "cost_cached": cost_cached, "cost_live": cost_live, "match_ok": sum(r["matched"] for r in rows), "n": len(rows)}
    (RES / "speed_cost.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
