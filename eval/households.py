"""End-to-end households: B's 20 synthetic policies x 10 households through B's engine.

Run twice: with B's 2024 synthetic FPL (should reproduce B's answer key) and with the real 2026 HHS table
(data/fpl_2026.json). Every combination whose answer changes under 2026 is listed for B to confirm;
the answer key is NOT edited.

python -m eval.households  -> eval/results/households.md
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path

from backend.eligibility import fpl_region_for_state, load_fpl_table_from_json
from backend.fpl import load_table
from billback.eligibility import EligibilityEngine, create_synthetic_resolver
from backend.policy_reader.cache import REPO_ROOT
from scripts.evaluate import compare_results, dict_to_household, dict_to_policy, result_to_dict

DATA = REPO_ROOT / "data"
OUT = REPO_ROOT / "eval" / "results" / "households.md"


def run(year: int, resolver, policies, households, key) -> tuple[int, int, dict, list]:
    engine = EligibilityEngine(resolver)
    ok, total, per_hh, rows = 0, 0, {}, []
    for pid, policy in policies.items():
        policy_y = dataclasses.replace(policy, default_fpl_year=year)
        for hid, hh in households.items():
            expected = key["results"][pid][hid]
            actual = result_to_dict(engine.evaluate(policy_y, hh, fpl_year=year))
            match, diffs = compare_results(expected, actual)
            total += 1
            ok += match
            per_hh.setdefault(hid, [0, 0])
            per_hh[hid][0] += match
            per_hh[hid][1] += 1
            rows.append((pid, hid, expected["status"], actual["status"], match, diffs))
    return ok, total, per_hh, rows


def main() -> int:
    key = json.loads((DATA / "answer_key.json").read_text())
    policies = {json.loads(p.read_text())["policy_id"]: dict_to_policy(json.loads(p.read_text()))
                for p in sorted((DATA / "policies").glob("HOSP-*.json"))}
    households = {json.loads(p.read_text())["household_id"]: dict_to_household(json.loads(p.read_text()))
                  for p in sorted((DATA / "households").glob("HH-*.json"))}
    real = load_table()

    ok24, n24, hh24, rows24 = run(2024, create_synthetic_resolver(2024), policies, households, key)
    ok26, n26, hh26, rows26 = run(int(real["year"]), load_fpl_table_from_json(real), policies, households, key)
    changed = [(a, b) for a, b in zip(rows24, rows26) if a[3] != b[3]]
    hh_all_ok = sum(1 for v in hh26.values() if v[0] == v[1])

    lines = [
        "# End-to-end households (B's engine)", "",
        f"B's {len(policies)} synthetic policies x {len(households)} households = {n26} combinations, compared with `data/answer_key.json` "
        "(status, matched tier, discount, missing facts, unresolved rules). Generated by `python -m eval.households`.", "",
        "| FPL table | Combinations matching the answer key | Households with all 20 policies matching |", "|---|---|---|",
        f"| 2024 synthetic (what B's key was built with) | {ok24}/{n24} | {sum(1 for v in hh24.values() if v[0] == v[1])}/{len(households)} |",
        f"| **2026 HHS (data/fpl_2026.json), used live** | **{ok26}/{n26}** | **{hh_all_ok}/{len(households)}** |", "",
        "## Per household (2026)", "", "| Household | Matching |", "|---|---|",
        *[f"| {h} | {v[0]}/{v[1]} |" for h, v in hh26.items()], "",
        f"## Answers that change when moving from 2024 to 2026 poverty numbers ({len(changed)}) — B please confirm", "",
        "| Policy | Household | Key (2024) | 2026 result |", "|---|---|---|---|",
        *[f"| {a[0]} | {a[1]} | {a[2]} | {b[3]} |" for a, b in changed],
    ]
    if not changed:
        lines.append("| — | none | | |")
    mism = [r for r in rows26 if not r[4] and r[2] == r[3]]
    if mism:
        lines += ["", f"## Same status but other details differ under 2026 ({len(mism)})", "",
                  "| Policy | Household | Difference |", "|---|---|---|",
                  *[f"| {r[0]} | {r[1]} | {'; '.join(r[5])[:160]} |" for r in mism[:40]]]
    OUT.write_text("\n".join(lines) + "\n")
    OUT.with_suffix(".json").write_text(json.dumps({"ok_2024": ok24, "ok_2026": ok26, "n": n26, "households_all_ok_2026": hh_all_ok,
                                                    "households": len(households), "status_changes": len(changed), "detail_diffs": len(mism),
                                                    "status_ok_2026": sum(1 for r in rows26 if r[2] == r[3]),
                                                    "households_status_ok_2026": sum(1 for h in households if all(r[2] == r[3] for r in rows26 if r[1] == h))}, indent=2) + "\n")
    print(f"2024: {ok24}/{n24}   2026: {ok26}/{n26}   households all-match (2026): {hh_all_ok}/{len(households)}   status changes: {len(changed)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
