"""Run the policy reader on B's real-policy list (data/real-policies/*.json -> source_url).

python -m eval.read_b_real_policies   (live: fetch each PDF + one model call, ~$0.04 each)
Results land in cache/policies/ like any other read; a status table goes to eval/results/b_real_policies.md.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

from backend.policy_reader.fetch import FetchError, fetch_policy_pdf
from backend.policy_reader.reader import read_policy
from backend.policy_reader.cache import REPO_ROOT

OUT = REPO_ROOT / "eval" / "results" / "b_real_policies.md"


def main() -> int:
    rows = []
    for path in sorted((REPO_ROOT / "data" / "real-policies").glob("HOSP-R*.json")):
        meta = json.loads(path.read_text())
        url = meta.get("source_url")
        start = time.perf_counter()
        try:
            pdf, final_url = fetch_policy_pdf(url)
            res = read_policy(pdf, url=final_url)
            r = res.rules
            rows.append([meta["policy_id"], meta["hospital_name"], meta["state"], "ok",
                         r.free_care.fpl_max_percent, r.discount.fpl_max_percent, r.uses_income_table,
                         len(r.review_fields), f"{time.perf_counter() - start:.1f}", ""])
        except (FetchError, Exception) as exc:  # report every failure; keep going
            rows.append([meta["policy_id"], meta["hospital_name"], meta["state"], "FAILED", "", "", "", "", f"{time.perf_counter() - start:.1f}", str(exc)[:90]])
        print(" | ".join(str(c) for c in rows[-1]), flush=True)
    ok = sum(1 for r in rows if r[3] == "ok")
    lines = ["# Policy reader on B's real-policy list", "", f"{ok}/{len(rows)} read successfully. Generated by `python -m eval.read_b_real_policies`.", "",
             "| id | hospital | state | status | free % | discount % | income table | review fields | sec | error |", "|---|---|---|---|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    OUT.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
