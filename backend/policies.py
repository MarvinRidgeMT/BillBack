"""Cached policies: load by slug, list hospitals, and match a bill's hospital to a cached policy.

cache/policies/index.json is generated by `python -m backend.policies --build-index` from the
cached rules JSON + data/policies/sources.csv + the hand-written aliases below.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Optional

from rapidfuzz import fuzz

from backend.policy_reader.cache import DEFAULT_CACHE_DIR, REPO_ROOT
from backend.policy_reader.schema import PolicyRules

INDEX_PATH = DEFAULT_CACHE_DIR / "index.json"
SOURCES_CSV = REPO_ROOT / "data" / "policies" / "sources.csv"
MATCH_THRESHOLD = 80
STATE_MISMATCH_PENALTY = 30
_SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,59}$")
_STATE_IN_ADDRESS_RE = re.compile(r"\b([A-Z]{2})\s+\d{5}(?:-\d{4})?\b")

# Other names the same policy covers (facilities, former names). States = where its facilities are.
ALIASES: dict[str, dict[str, Any]] = {
    "usa-health": {"aliases": ["University of South Alabama", "USA Health University Hospital",
                               "USA Health Children's & Women's Hospital", "USA Health Providence Hospital"],
                   "city": "Mobile", "states": ["AL"]},
    "baptist-memorial-health-care-corporation": {"aliases": ["Baptist Memorial Health Care", "Baptist Memorial Hospital",
                                                             "OCH Regional Medical Center", "Baptist Memorial Hospital-Golden Triangle"],
                                                 "city": "Memphis", "states": ["TN", "MS", "AR"]},
    "boys-town-national-research-hospital": {"aliases": ["Boys Town Hospital", "Boys Town National Research Hospital - West"],
                                             "city": "Omaha", "states": ["NE"]},
    "fort-healthcare-inc": {"aliases": ["Fort HealthCare", "Fort Memorial Hospital"], "city": "Fort Atkinson", "states": ["WI"]},
    "marshfield-clinic-health-system": {"aliases": ["Marshfield Clinic", "Marshfield Medical Center"],
                                        "city": "Marshfield", "states": ["WI", "MI"]},
    "adena-health-system": {"aliases": ["Adena Regional Medical Center", "Adena Health"], "city": "Chillicothe", "states": ["OH"]},
    # The policy names no state; Banner is headquartered in Phoenix and runs hospitals in these states.
    "banner-health": {"aliases": ["Banner University Medical Center", "Banner Desert Medical Center"],
                      "city": "Phoenix", "state": "AZ", "states": ["AZ", "CO", "NE", "WY", "CA", "NV"]},
}


# Made-up hospitals on fictional demo bills -> a real cached policy in the same state, so the demo can finish.
DEMO_ALIASES: dict[str, str] = {
    "Lakeside Pretend Medical Center": "marshfield-clinic-health-system",  # frontend/public/samples/sample-bill.png (WI)
    "Sample General Hospital (Fictional)": "adena-health-system",  # backend/tests/fixtures/bills/bill_a_text.pdf (OH)
}


def load_policy(slug: str, cache_dir: Path = DEFAULT_CACHE_DIR) -> tuple[PolicyRules, Path]:
    """Load cache/policies/<slug>__<sha8>.json. The slug is validated so it can't escape the folder."""
    if not isinstance(slug, str) or not _SLUG_RE.match(slug):
        raise ValueError("hospital_slug must be lowercase letters, digits and dashes")
    matches = sorted(Path(cache_dir).glob(f"{slug}__*.json"))
    if not matches:
        raise LookupError(f"no cached policy for '{slug}'")
    return PolicyRules.model_validate_json(matches[0].read_text()), matches[0]


def _sources_by_sha() -> dict[str, dict[str, str]]:
    import hashlib

    out: dict[str, dict[str, str]] = {}
    if not SOURCES_CSV.exists():
        return out
    with SOURCES_CSV.open() as fh:
        for row in csv.DictReader(fh):
            pdf = SOURCES_CSV.parent / row["file"]
            if pdf.exists():
                out[hashlib.sha256(pdf.read_bytes()).hexdigest()] = row
    return out


def build_index(cache_dir: Path = DEFAULT_CACHE_DIR) -> list[dict[str, Any]]:
    sources = _sources_by_sha()
    entries = []
    for path in sorted(Path(cache_dir).glob("*__*.json")):
        rules = PolicyRules.model_validate_json(path.read_text())
        slug = path.name.split("__")[0]
        extra = ALIASES.get(slug, {})
        src = sources.get(rules.source.sha256, {}) if rules.source else {}
        entries.append(
            {
                "slug": slug,
                "hospital_name": rules.hospital_name,
                "aliases": extra.get("aliases", []) + [name for name, target in DEMO_ALIASES.items() if target == slug],
                "city": extra.get("city"),
                "state": rules.hospital_state or extra.get("state"),
                "states": extra.get("states", [rules.hospital_state] if rules.hospital_state else []),
                "file": path.name,
                "source_url": (rules.source.url if rules.source else None) or src.get("url"),
                "downloaded": src.get("downloaded"),
                "needs_human_review": rules.needs_human_review,
            }
        )
    return entries


@lru_cache(maxsize=1)
def load_index() -> tuple[dict[str, Any], ...]:
    if INDEX_PATH.exists():
        return tuple(json.loads(INDEX_PATH.read_text())["hospitals"])
    return tuple(build_index())


def list_hospitals() -> list[dict[str, Any]]:
    return [{"slug": h["slug"], "name": h["hospital_name"], "state": h["state"]} for h in load_index()]


def source_url_for(rules: PolicyRules) -> Optional[str]:
    if rules.source is None:
        return None
    if rules.source.url:
        return rules.source.url
    for h in load_index():
        if rules.source.sha256.startswith(h["file"].split("__")[1].removesuffix(".json")):
            return h["source_url"]
    return None


def _state_from_address(address: Optional[str]) -> Optional[str]:
    if not address:
        return None
    found = _STATE_IN_ADDRESS_RE.findall(address.upper())
    return found[-1] if found else None


def match_hospital(name: Optional[str], address: Optional[str] = None) -> dict[str, Any]:
    """Top match for a bill's hospital. score 0-100; matched=False below MATCH_THRESHOLD -> 'not in our list'."""
    if not name or not name.strip():
        return {"matched": False, "slug": None, "hospital_name": None, "score": 0, "reason": "no hospital name on the bill"}
    bill_state = _state_from_address(address)
    best: dict[str, Any] = {"slug": None, "hospital_name": None, "score": 0.0}
    for h in load_index():
        names = [h["hospital_name"], *h["aliases"]]
        score = max(fuzz.token_set_ratio(name.lower(), n.lower()) for n in names)
        if bill_state and h["states"] and bill_state not in h["states"]:
            score -= STATE_MISMATCH_PENALTY
        if score > best["score"]:
            best = {"slug": h["slug"], "hospital_name": h["hospital_name"], "score": score}
    matched = best["score"] >= MATCH_THRESHOLD
    return {
        **best,
        "score": round(best["score"], 1),
        "matched": matched,
        "bill_state": bill_state,
        "reason": None if matched else "not in our list; pick the hospital or paste its policy link",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build cache/policies/index.json")
    parser.add_argument("--build-index", action="store_true")
    if parser.parse_args().build_index:
        INDEX_PATH.write_text(json.dumps({"hospitals": build_index()}, indent=2) + "\n")
        print(f"wrote {INDEX_PATH} ({len(build_index())} hospitals)")
