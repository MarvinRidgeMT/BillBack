# Made-up hospitals on fictional demo bills -> a real cached policy in the same state, so the demo can finish.
DEMO_ALIASES: dict[str, str] = {
    "Lakeside Pretend Medical Center": "marshfield-clinic-health-system",  # frontend/public/samples/sample-bill.png (WI)
    "Sample General Hospital (Fictional)": "adena-health-system",  # backend/tests/fixtures/bills/bill_a_text.pdf (OH)
}


def load_policy(slug: str, cache_dir: Path = DEFAULT_CACHE_DIR) -> tuple[PolicyRules, Optional[Path]]:
    """Load cache/policies/<slug>__<sha8>.json, or a live-mode policy from memory ("live-..." slugs, no file).
    The slug is validated so it can't escape the folder."""
    if not isinstance(slug, str) or not _SLUG_RE.match(slug):
        raise ValueError("hospital_slug must be lowercase letters, digits and dashes")
    if live_session.is_live_slug(slug):
        rules = live_session.get(slug)
        if rules is None:
            raise LookupError(f"'{slug}' has expired; read the policy again")
        return rules, None
    matches = sorted(Path(cache_dir).glob(f"{slug}__*.json"))
    if not matches:
        raise LookupError(f"no cached policy for '{slug}'")
    return PolicyRules.model_validate_json(matches[0].read_text()), matches[0]


def _sources_by_sha() -> dict[str, dict[str, str]]:
    import hashlib

    out: dict[str, dict[str, str]] = {}
    if not SOURCES_CSV.exists():
        return out
    with SOURCES_CSV.open() as fh:
        for row in csv.DictReader(fh):
            pdf = SOURCES_CSV.parent / row["file"]
            if pdf.exists():
                out[hashlib.sha256(pdf.read_bytes()).hexdigest()] = row
    return out


def build_index(cache_dir: Path = DEFAULT_CACHE_DIR) -> list[dict[str, Any]]:
    sources = _sources_by_sha()
    entries = []
    for path in sorted(Path(cache_dir).glob("*__*.json")):
        rules = PolicyRules.model_validate_json(path.read_text())
        slug = path.name.split("__")[0]
        extra = ALIASES.get(slug, {})
        src = sources.get(rules.source.sha256, {}) if rules.source else {}
        entries.append(
            {
                "slug": slug,
                "hospital_name": rules.hospital_name,
                "aliases": extra.get("aliases", []) + [name for name, target in DEMO_ALIASES.items() if target == slug],
                "city": extra.get("city"),
                "state": rules.hospital_state or extra.get("state"),
                "states": extra.get("states", [rules.hospital_state] if rules.hospital_state else []),
                "file": path.name,
                "source_url": (rules.source.url if rules.source else None) or src.get("url"),
                "downloaded": src.get("downloaded"),
                "needs_human_review": rules.needs_human_review,
            }
        )
    return entries


@lru_cache(maxsize=1)
def load_index() -> tuple[dict[str, Any], ...]:
    if INDEX_PATH.exists():
        return tuple(json.loads(INDEX_PATH.read_text())["hospitals"])
    return tuple(build_index())


def _limits(slug: str) -> dict[str, Any]:
    """Free-care and discount limits (% of the poverty line) for the charity-care map. Additive fields."""
    try:
        rules, _ = load_policy(slug)
    except (ValueError, LookupError):
        return {"free_max_percent": None, "discount_max_percent": None}
    tier_max = [t.fpl_max_percent for t in rules.discount.tiers if t.fpl_max_percent is not None]
    return {
        "free_max_percent": rules.free_care.fpl_max_percent,
        "discount_max_percent": rules.discount.fpl_max_percent or (max(tier_max) if tier_max else None),
    }


def list_hospitals() -> list[dict[str, Any]]:
    return [
        {"slug": h["slug"], "name": h["hospital_name"], "state": h["state"], "source_url": h.get("source_url"), **_limits(h["slug"])}
        for h in load_index()
    ]


def source_url_for(rules: PolicyRules) -> Optional[str]:
    if rules.source is None:
        return None
    if rules.source.url:
        return rules.source.url
    for h in load_index():
        if rules.source.sha256.startswith(h["file"].split("__")[1].removesuffix(".json")):
            return h["source_url"]
    return None


def _state_from_address(address: Optional[str]) -> Optional[str]:
    if not address:
        return None
    found = _STATE_IN_ADDRESS_RE.findall(address.upper())
    return found[-1] if found else None


def match_hospital(name: Optional[str], address: Optional[str] = None) -> dict[str, Any]:
    """Top match for a bill's hospital. score 0-100; matched=False below MATCH_THRESHOLD -> 'not in our list'."""
    if not name or not name.strip():
        return {"matched": False, "slug": None, "hospital_name": None, "score": 0, "reason": "no hospital name on the bill"}
    bill_state = _state_from_address(address)
    best: dict[str, Any] = {"slug": None, "hospital_name": None, "score": 0.0}
    for h in load_index():
        names = [h["hospital_name"], *h["aliases"]]
        score = max(fuzz.token_set_ratio(name.lower(), n.lower()) for n in names)
        if bill_state and h["states"] and bill_state not in h["states"]:
            score -= STATE_MISMATCH_PENALTY
        if score > best["score"]:
            best = {"slug": h["slug"], "hospital_name": h["hospital_name"], "score": score}
    matched = best["score"] >= MATCH_THRESHOLD
    return {
        **best,
        "score": round(best["score"], 1),
        "matched": matched,
        "bill_state": bill_state,
        "reason": None if matched else "not in our list; pick the hospital or paste its policy link",
    }


SEARCH_MIN_SCORE = 60
SEARCH_LIMIT = 8


def curated_slug_for_url(url: Optional[str]) -> Optional[str]:
    """The curated policy whose public PDF is this URL (live mode falls back to it if the model is down)."""
    if not url:
        return None
    wanted = url.strip().rstrip("/").lower()
    for h in load_index():
        if h.get("source_url") and h["source_url"].strip().rstrip("/").lower() == wanted:
            return h["slug"]
    return None


WORD_MATCH_MIN = 80


def _search_score(query: str, h: dict[str, Any]) -> float:
    """Every word of the query must fuzzily match a word of the hospital's names, city or state; then rank by
    whole-name similarity. 'Mayo Clinic' must not match 'Marshfield Clinic' just because both say 'clinic'."""
    states = [s for s in [h.get("state"), *h.get("states", [])] if s]
    names = [h["hospital_name"], *h.get("aliases", [])]
    hay = " ".join([*names, h.get("city") or "", *states]).lower().replace("'", "").split()
    words = query.lower().replace("'", "").split()
    if not words:
        return 0.0
    covered = sum(max(fuzz.ratio(w, x) for x in hay) >= WORD_MATCH_MIN for w in words) / len(words)
    whole = max(
        max(fuzz.token_sort_ratio(query.lower(), n.lower()) for n in names),
        max(fuzz.partial_token_sort_ratio(query.lower(), n.lower()) for n in names) if len(query) >= 4 else 0,
        fuzz.token_sort_ratio(query.lower(), (h.get("city") or "").lower()),
    )
    return max(whole, 90.0) if covered == 1 else covered * 50  # partial coverage stays under SEARCH_MIN_SCORE


def search_hospitals(query: Optional[str], limit: int = SEARCH_LIMIT) -> list[dict[str, Any]]:
    """Fuzzy search over curated hospitals: name, other names, city and state. A bare state code lists that state."""
    q = (query or "").strip()[:100]
    if len(q) < 2:
        return []
    results = []
    for h in load_index():
        states = [s for s in [h.get("state"), *h.get("states", [])] if s]
        score = 100.0 if len(q) == 2 and q.upper() in states else _search_score(q, h)
        if score >= SEARCH_MIN_SCORE:
            results.append({"slug": h["slug"], "name": h["hospital_name"], "state": h.get("state"),
                            "city": h.get("city"), "score": round(score, 1)})
    results.sort(key=lambda r: (-r["score"], r["name"]))
    return results[:limit]


